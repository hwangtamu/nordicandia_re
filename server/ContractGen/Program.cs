var ordered = new List<TypeDefinition>();
while (q.Count > 0)
{
    var tr = q.Dequeue();
    if (tr is null) continue;
    if (tr is GenericInstanceType gi) { foreach (var a in gi.GenericArguments) Enq(a); tr = gi.ElementType; }
    else if (tr is ArrayType at) { Enq(at.ElementType); continue; }
    else if (tr is ByReferenceType br) { Enq(br.ElementType); continue; }
    else if (tr is PointerType pt) { Enq(pt.ElementType); continue; }
    if (byName.TryGetValue(tr.FullName, out var td))
    {
        if (!seen.Add(td.FullName)) continue;
        ordered.Add(td);
        if (td.BaseType != null) Enq(td.BaseType);
        foreach (var f in td.Fields) { if (f.IsStatic) continue; Enq(f.FieldType); }
        foreach (var p in td.Properties) Enq(p.PropertyType);
        foreach (var a in td.CustomAttributes) foreach (var ca in a.ConstructorArguments) Enq(ca.Value as TypeReference);
    }
}

