string ElementName(TypeReference tr)
{
    if (tr.IsNested && tr.DeclaringType != null) return ElementName(tr.DeclaringType) + "." + SimpleName(tr);
    var ns = tr.Namespace;
    var name = SimpleName(tr);
    return string.IsNullOrEmpty(ns) ? name : ns + "." + name;
}
string SimpleName(TypeReference tr)
{
    var n = tr.Name;
    var tick = n.IndexOf('`');
    if (tick >= 0) n = n.Substring(0, tick);
    return n;
}
string Render(TypeReference tr)
{
    if (tr is GenericParameter gp) return gp.Name;
    if (tr is ArrayType at) return Render(at.ElementType) + "[" + new string(',', at.Rank - 1) + "]";
    if (tr is ByReferenceType br) return Render(br.ElementType);
    if (tr is GenericInstanceType gi)
    {
        if (gi.ElementType.FullName == "System.Nullable`1")
            return Render(gi.GenericArguments[0]) + "?";
        var baseName = ElementName(gi.ElementType);
        var args = string.Join(", ", gi.GenericArguments.Select(Render));
        return baseName + "<" + args + ">";
    }
    if (prim.TryGetValue(tr.FullName, out var p)) return p;
    // nested
    if (tr.IsNested && tr.DeclaringType != null) return Render(tr.DeclaringType) + "." + SimpleName(tr);
    var ns = tr.Namespace;
    var name = SimpleName(tr);
    if (tr.HasGenericParameters) name += "<" + string.Join(", ", tr.GenericParameters.Select(g => g.Name)) + ">";
    return string.IsNullOrEmpty(ns) ? name : ns + "." + name;
}

