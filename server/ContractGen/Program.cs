string CtorArg(ICustomAttribute a, int i)
{
    if (a.ConstructorArguments.Count <= i) return null;
    var v = a.ConstructorArguments[i].Value;
    if (v is bool b) return b ? "true" : "false";
    return v?.ToString();
}
void EmitTypeAttrs(IndentWriter w, TypeDefinition td)
{
    if (td.FullName == "Game.GameAttributeValue") w.Line("[MessagePackFormatter(typeof(Nordicandia.Contracts.AttributeValueFormatter))]");
    if (td.FullName == "Game.GameAttributeValueDoubleArray") w.Line("[MessagePackFormatter(typeof(Nordicandia.Contracts.AttributeArrayFormatter))]");
    var mp = td.CustomAttributes.FirstOrDefault(a => a.AttributeType.Name == "MessagePackObjectAttribute");
    if (mp != null)
    {
        var k = CtorArg(mp, 0);
        w.Line(k == null ? "[MessagePackObject]" : $"[MessagePackObject({k})]");
    }
    foreach (var u in td.CustomAttributes.Where(a => a.AttributeType.Name == "UnionAttribute"))
    {
        var idx = u.ConstructorArguments[0].Value;
        var ty = u.ConstructorArguments[1].Value as TypeReference;
        w.Line($"[Union({idx}, typeof({Render(ty!)}))]");
    }
    if (td.CustomAttributes.Any(a => a.AttributeType.Name == "DataContractAttribute")) w.Line("[System.Runtime.Serialization.DataContract]");
}
void EmitMemberAttrs(IndentWriter w, ICustomAttributeProvider p)
{
    foreach (var a in p.CustomAttributes)
    {
        if (a.AttributeType.Name == "KeyAttribute")
        {
            var ca = a.ConstructorArguments[0];
            w.Line(ca.Type.FullName == "System.String" ? $"[Key(\"{ca.Value}\")]" : $"[Key({ca.Value})]");
        }
        else if (a.AttributeType.Name == "IgnoreMemberAttribute") w.Line("[IgnoreMember]");
        else if (a.AttributeType.Name == "DataMemberAttribute") w.Line("[System.Runtime.Serialization.DataMember]");
    }
}

void Emit(TypeDefinition td, IndentWriter w)
{
    // generics
    var gen = td.HasGenericParameters ? "<" + string.Join(", ", td.GenericParameters.Select(g => g.Name)) + ">" : "";
    if (td.IsEnum)
    {
        var underlying = td.Fields.FirstOrDefault(f => f.Name == "value__");
        var und = underlying != null ? Render(underlying.FieldType) : "int";
        EmitTypeAttrs(w, td);
        w.Line($"public enum {SimpleName(td)}{gen} : {und}");
        w.BraceOpen();
        foreach (var f in td.Fields.Where(f => f.IsStatic && f.HasConstant))
            w.Line($"{f.Name} = {f.Constant},");
        w.BraceClose();
        return;
    }
    var kind = td.IsInterface ? "interface" : td.IsValueType ? "struct" : "class";
    var mods = "public ";
    if (td.IsAbstract && !td.IsInterface) mods += "abstract ";
    if (td.IsSealed && !td.IsValueType && !td.IsAbstract) mods += "sealed ";
    var baseType = "";
    if (td.BaseType != null && td.BaseType.FullName is not ("System.Object" or "System.ValueType" or "System.Enum"))
        baseType = " : " + Render(td.BaseType);
    if (td.Interfaces.Any(i => i.InterfaceType.FullName == "SharedNet.Dto.Realtime.Message")) baseType += (baseType == "" ? " : " : ", ") + "SharedNet.Dto.Realtime.Message";
    EmitTypeAttrs(w, td);
    w.Line($"{mods}{kind} {SimpleName(td)}{gen}{baseType}");
    w.BraceOpen();
    if (td.FullName == "Game.GameAttributeValueDoubleArray") w.Line("[IgnoreMember] public byte[] WireData { get; set; }");
    // nested types first
    foreach (var nt in td.NestedTypes) Emit(nt, w);
    if (td.IsValueType)
    {
        foreach (var f in td.Fields.Where(f => !f.IsStatic && !f.IsLiteral))
        {
            if (f.Name.StartsWith("<") || f.Name.Contains("k__BackingField")) continue;
            EmitMemberAttrs(w, f);
            if (td.FullName == "Game.GameAttributeValue" && f.Name == "_ValueD" && !f.CustomAttributes.Any(a => a.AttributeType.Name == "IgnoreMemberAttribute")) w.Line("[IgnoreMember]");
            w.Line($"public {Render(f.FieldType)} {f.Name};");
        }
    }
    foreach (var p in td.Properties)
    {
        // `Item` used to be skipped wholesale, which silently dropped
        // AddItemOperationEntry.Item (the only place the client sends full item
        // payloads). Keep the exception narrow so other generated DTOs are unaffected.
        if (p.Name == "Item" && td.FullName != "SharedNet.Api.AddItemOperationEntry") continue;
        var backed = td.Fields.FirstOrDefault(f => f.Name == "<" + p.Name + ">k__BackingField");
        var hasMpAttr = p.CustomAttributes.Any(a => a.AttributeType.Name is "KeyAttribute" or "IgnoreMemberAttribute");
        if (hasMpAttr || backed == null) EmitMemberAttrs(w, p);
        else EmitMemberAttrs(w, backed);
        var hasSet = p.SetMethod != null;
        var acc = hasSet ? "{ get; set; }" : "{ get; }";
        w.Line($"public {Render(p.PropertyType)} {p.Name} {acc}");
    }
    // ensure parameterless ctor exists
    if (!td.IsInterface && !td.IsAbstract && !td.IsValueType && !td.Methods.Any(m => m.IsConstructor && !m.IsStatic && m.Parameters.Count == 0))
        w.Line($"public {SimpleName(td)}() {{ }}");
    w.BraceClose();
}

