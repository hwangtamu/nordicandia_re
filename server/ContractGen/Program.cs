public sealed class IndentWriter
{
    private readonly StringBuilder _sb; private readonly int _indent;
    public IndentWriter(StringBuilder sb, int indent) { _sb = sb; _indent = indent; }
    public void Line(string s) => _sb.Append(new string(' ', _indent)).AppendLine(s);
    public void BraceOpen() => _sb.Append(new string(' ', _indent)).AppendLine("{");
    public void BraceClose() => _sb.Append(new string(' ', _indent)).AppendLine("}");
}
